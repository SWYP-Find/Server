-- 3) (user_id, battle_id) UK → (user_id, battle_id, class_id) 교체
--    class_id NULL(일반 배틀)끼리도 중복을 막아야 하므로 NULLS NOT DISTINCT 사용.
--    엔티티 @UniqueConstraint(uk_*_user_battle_class)는 Hibernate 가 매 기동마다 drop/recreate 하므로
--    여기서는 별도 이름(ux_*_nn)으로 만든다.
ALTER TABLE user_battles DROP CONSTRAINT IF EXISTS uk_user_battle;
DROP INDEX IF EXISTS uk_user_battle;

CREATE UNIQUE INDEX IF NOT EXISTS ux_user_battles_user_battle_class_nn
    ON user_battles (user_id, battle_id, class_id) NULLS NOT DISTINCT;
CREATE UNIQUE INDEX IF NOT EXISTS ux_votes_user_battle_class_nn
    ON votes (user_id, battle_id, class_id) NULLS NOT DISTINCT;

-- 4) partial / NULLS NOT DISTINCT unique index (JPA 로 표현 불가)
-- 계정당 ACTIVE 이용권 1개
CREATE UNIQUE INDEX IF NOT EXISTS ux_class_tickets_active_user
    ON class_tickets (registered_user_id) WHERE status = 'ACTIVE';
-- 클래스 내 ACTIVE 멤버 별칭 중복 불가
CREATE UNIQUE INDEX IF NOT EXISTS ux_class_members_active_display_name
    ON class_members (class_id, display_name) WHERE status = 'ACTIVE';
-- 리포트는 (class, member, type) 당 1건. CLASS_SUMMARY 는 member NULL
CREATE UNIQUE INDEX IF NOT EXISTS ux_class_reports_class_member_type
    ON class_reports (class_id, member_id, type) NULLS NOT DISTINCT;

