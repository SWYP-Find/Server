-- ddl-auto(update) 가 못 하는 변경(UK 교체, partial / NULLS NOT DISTINCT 인덱스, 기본값 백필)을 포함한다.
-- 앱 기동 전에 1회 실행. 멱등하게 작성되어 재실행해도 안전하다.
-- 요구 버전: PostgreSQL 15+ (UNIQUE ... NULLS NOT DISTINCT)

-- 0) 기존 테이블 컬럼 추가
ALTER TABLE battles ADD COLUMN IF NOT EXISTS difficulty VARCHAR(20);
ALTER TABLE battles ADD COLUMN IF NOT EXISTS category VARCHAR(30);
ALTER TABLE battles ADD COLUMN IF NOT EXISTS class_recommendable BOOLEAN NOT NULL DEFAULT FALSE;
ALTER TABLE battles ADD COLUMN IF NOT EXISTS mid_vote_enabled BOOLEAN NOT NULL DEFAULT FALSE;

ALTER TABLE votes ADD COLUMN IF NOT EXISTS class_id BIGINT;
ALTER TABLE votes ADD COLUMN IF NOT EXISTS mid_vote_option_id BIGINT;

ALTER TABLE perspectives ADD COLUMN IF NOT EXISTS class_id BIGINT;
ALTER TABLE perspective_comments ADD COLUMN IF NOT EXISTS class_id BIGINT;
ALTER TABLE user_battles ADD COLUMN IF NOT EXISTS class_id BIGINT;

-- 1) 신규 테이블
CREATE TABLE IF NOT EXISTS funding_orders (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    platform VARCHAR(20) NOT NULL,
    campaign_id VARCHAR(50) NOT NULL,
    order_id VARCHAR(50) NOT NULL,
    reward_tier VARCHAR(10) NOT NULL,
    quantity INTEGER NOT NULL,
    supporter_name VARCHAR(50) NOT NULL,
    supporter_email VARCHAR(255),
    supporter_phone VARCHAR(20),
    payment_status VARCHAR(20) NOT NULL,
    paid_at TIMESTAMP,
    import_file_hash VARCHAR(64),
    created_at TIMESTAMP,
    updated_at TIMESTAMP,
    CONSTRAINT uk_funding_orders_order_id UNIQUE (order_id)
);

CREATE TABLE IF NOT EXISTS class_tickets (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    funding_order_id BIGINT NOT NULL,
    capacity INTEGER NOT NULL,
    code_hash VARCHAR(64) NOT NULL,
    code_status VARCHAR(20) NOT NULL,
    delivered_at TIMESTAMP,
    register_by TIMESTAMP NOT NULL,
    registered_user_id BIGINT,
    activated_at TIMESTAMP,
    expires_at TIMESTAMP,
    status VARCHAR(20) NOT NULL,
    revoked_at TIMESTAMP,
    created_at TIMESTAMP,
    updated_at TIMESTAMP,
    CONSTRAINT uk_class_tickets_funding_order UNIQUE (funding_order_id),
    CONSTRAINT uk_class_tickets_code_hash UNIQUE (code_hash)
);

CREATE TABLE IF NOT EXISTS ticket_delivery_attempts (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    ticket_id BIGINT NOT NULL,
    channel VARCHAR(20) NOT NULL,
    status VARCHAR(20) NOT NULL,
    failure_reason VARCHAR(255),
    attempted_at TIMESTAMP NOT NULL,
    created_at TIMESTAMP,
    updated_at TIMESTAMP
);

CREATE TABLE IF NOT EXISTS classes (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name VARCHAR(20) NOT NULL,
    invite_code VARCHAR(6) NOT NULL,
    owner_id BIGINT NOT NULL,
    ticket_id BIGINT NOT NULL,
    battle_id BIGINT NOT NULL,
    battle_type VARCHAR(10) NOT NULL,
    capacity INTEGER NOT NULL,
    deadline TIMESTAMP,
    comment_required BOOLEAN NOT NULL,
    owner_participates BOOLEAN NOT NULL,
    status VARCHAR(20) NOT NULL,
    deleted_at TIMESTAMP,
    created_at TIMESTAMP,
    updated_at TIMESTAMP,
    CONSTRAINT uk_classes_invite_code UNIQUE (invite_code)
);

CREATE TABLE IF NOT EXISTS class_members (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    class_id BIGINT NOT NULL,
    user_id BIGINT NOT NULL,
    display_name VARCHAR(20) NOT NULL,
    role VARCHAR(10) NOT NULL,
    status VARCHAR(10) NOT NULL,
    seat_held BOOLEAN NOT NULL,
    joined_at TIMESTAMP NOT NULL,
    left_at TIMESTAMP,
    created_at TIMESTAMP,
    updated_at TIMESTAMP,
    CONSTRAINT uk_class_members_class_user UNIQUE (class_id, user_id)
);

CREATE TABLE IF NOT EXISTS ai_jobs (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    type VARCHAR(30) NOT NULL,
    status VARCHAR(20) NOT NULL,
    idempotency_key VARCHAR(100) NOT NULL,
    ticket_id BIGINT,
    class_id BIGINT,
    member_id BIGINT,
    model VARCHAR(50),
    input_tokens INTEGER,
    output_tokens INTEGER,
    attempt INTEGER NOT NULL,
    error_code VARCHAR(50),
    started_at TIMESTAMP,
    finished_at TIMESTAMP,
    created_at TIMESTAMP,
    updated_at TIMESTAMP,
    CONSTRAINT uk_ai_jobs_idempotency_key UNIQUE (idempotency_key)
);

CREATE TABLE IF NOT EXISTS class_reports (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    class_id BIGINT NOT NULL,
    member_id BIGINT,
    type VARCHAR(20) NOT NULL,
    status VARCHAR(20) NOT NULL,
    content JSONB,
    ai_job_id BIGINT,
    generated_at TIMESTAMP,
    created_at TIMESTAMP,
    updated_at TIMESTAMP
);

-- 2) FK
DO $$
BEGIN
    -- 기존 테이블 → classes / battle_options
    IF NOT EXISTS (SELECT 1 FROM pg_constraint WHERE conname = 'fk_votes_class') THEN
        ALTER TABLE votes ADD CONSTRAINT fk_votes_class
            FOREIGN KEY (class_id) REFERENCES classes(id);
    END IF;
    IF NOT EXISTS (SELECT 1 FROM pg_constraint WHERE conname = 'fk_votes_mid_vote_option') THEN
        ALTER TABLE votes ADD CONSTRAINT fk_votes_mid_vote_option
            FOREIGN KEY (mid_vote_option_id) REFERENCES battle_options(id);
    END IF;
    IF NOT EXISTS (SELECT 1 FROM pg_constraint WHERE conname = 'fk_perspectives_class') THEN
        ALTER TABLE perspectives ADD CONSTRAINT fk_perspectives_class
            FOREIGN KEY (class_id) REFERENCES classes(id);
    END IF;
    IF NOT EXISTS (SELECT 1 FROM pg_constraint WHERE conname = 'fk_perspective_comments_class') THEN
        ALTER TABLE perspective_comments ADD CONSTRAINT fk_perspective_comments_class
            FOREIGN KEY (class_id) REFERENCES classes(id);
    END IF;
    IF NOT EXISTS (SELECT 1 FROM pg_constraint WHERE conname = 'fk_user_battles_class') THEN
        ALTER TABLE user_battles ADD CONSTRAINT fk_user_battles_class
            FOREIGN KEY (class_id) REFERENCES classes(id);
    END IF;

    -- 이용권
    IF NOT EXISTS (SELECT 1 FROM pg_constraint WHERE conname = 'fk_class_tickets_funding_order') THEN
        ALTER TABLE class_tickets ADD CONSTRAINT fk_class_tickets_funding_order
            FOREIGN KEY (funding_order_id) REFERENCES funding_orders(id);
    END IF;
    IF NOT EXISTS (SELECT 1 FROM pg_constraint WHERE conname = 'fk_class_tickets_registered_user') THEN
        ALTER TABLE class_tickets ADD CONSTRAINT fk_class_tickets_registered_user
            FOREIGN KEY (registered_user_id) REFERENCES users(id);
    END IF;
    IF NOT EXISTS (SELECT 1 FROM pg_constraint WHERE conname = 'fk_ticket_delivery_attempts_ticket') THEN
        ALTER TABLE ticket_delivery_attempts ADD CONSTRAINT fk_ticket_delivery_attempts_ticket
            FOREIGN KEY (ticket_id) REFERENCES class_tickets(id) ON DELETE CASCADE;
    END IF;

    -- 클래스
    IF NOT EXISTS (SELECT 1 FROM pg_constraint WHERE conname = 'fk_classes_owner') THEN
        ALTER TABLE classes ADD CONSTRAINT fk_classes_owner
            FOREIGN KEY (owner_id) REFERENCES users(id);
    END IF;
    IF NOT EXISTS (SELECT 1 FROM pg_constraint WHERE conname = 'fk_classes_ticket') THEN
        ALTER TABLE classes ADD CONSTRAINT fk_classes_ticket
            FOREIGN KEY (ticket_id) REFERENCES class_tickets(id);
    END IF;
    IF NOT EXISTS (SELECT 1 FROM pg_constraint WHERE conname = 'fk_classes_battle') THEN
        ALTER TABLE classes ADD CONSTRAINT fk_classes_battle
            FOREIGN KEY (battle_id) REFERENCES battles(id);
    END IF;
    IF NOT EXISTS (SELECT 1 FROM pg_constraint WHERE conname = 'fk_class_members_class') THEN
        ALTER TABLE class_members ADD CONSTRAINT fk_class_members_class
            FOREIGN KEY (class_id) REFERENCES classes(id) ON DELETE CASCADE;
    END IF;
    IF NOT EXISTS (SELECT 1 FROM pg_constraint WHERE conname = 'fk_class_members_user') THEN
        ALTER TABLE class_members ADD CONSTRAINT fk_class_members_user
            FOREIGN KEY (user_id) REFERENCES users(id);
    END IF;

    -- AI
    IF NOT EXISTS (SELECT 1 FROM pg_constraint WHERE conname = 'fk_ai_jobs_ticket') THEN
        ALTER TABLE ai_jobs ADD CONSTRAINT fk_ai_jobs_ticket
            FOREIGN KEY (ticket_id) REFERENCES class_tickets(id);
    END IF;
    IF NOT EXISTS (SELECT 1 FROM pg_constraint WHERE conname = 'fk_ai_jobs_class') THEN
        ALTER TABLE ai_jobs ADD CONSTRAINT fk_ai_jobs_class
            FOREIGN KEY (class_id) REFERENCES classes(id);
    END IF;
    IF NOT EXISTS (SELECT 1 FROM pg_constraint WHERE conname = 'fk_ai_jobs_member') THEN
        ALTER TABLE ai_jobs ADD CONSTRAINT fk_ai_jobs_member
            FOREIGN KEY (member_id) REFERENCES class_members(id);
    END IF;
    IF NOT EXISTS (SELECT 1 FROM pg_constraint WHERE conname = 'fk_class_reports_class') THEN
        ALTER TABLE class_reports ADD CONSTRAINT fk_class_reports_class
            FOREIGN KEY (class_id) REFERENCES classes(id) ON DELETE CASCADE;
    END IF;
    IF NOT EXISTS (SELECT 1 FROM pg_constraint WHERE conname = 'fk_class_reports_member') THEN
        ALTER TABLE class_reports ADD CONSTRAINT fk_class_reports_member
            FOREIGN KEY (member_id) REFERENCES class_members(id);
    END IF;
    IF NOT EXISTS (SELECT 1 FROM pg_constraint WHERE conname = 'fk_class_reports_ai_job') THEN
        ALTER TABLE class_reports ADD CONSTRAINT fk_class_reports_ai_job
            FOREIGN KEY (ai_job_id) REFERENCES ai_jobs(id);
    END IF;
