-- #545 커스텀 배틀 AI 주제 제안·수정 검증 (docs/erd/class.puml 기준)
-- ddl-auto(update) 로도 테이블은 생기지만 FK·인덱스를 명시하기 위해 함께 둔다. 멱등하게 작성되어 재실행해도 안전하다.

CREATE TABLE IF NOT EXISTS class_topic_drafts (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    owner_id BIGINT NOT NULL,
    ticket_id BIGINT NOT NULL,
    topic_seed VARCHAR(200) NOT NULL,
    difficulty VARCHAR(20) NOT NULL,
    categories JSONB NOT NULL,
    suggest_status VARCHAR(30) NOT NULL,
    candidates JSONB,
    batch_no INTEGER NOT NULL DEFAULT 0,
    suggest_request_count INTEGER NOT NULL DEFAULT 0,
    suggest_started_at TIMESTAMP,
    clarification_message VARCHAR(200),
    validation_count INTEGER NOT NULL DEFAULT 0,
    created_at TIMESTAMP,
    updated_at TIMESTAMP
);

CREATE TABLE IF NOT EXISTS class_topic_versions (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    draft_id BIGINT NOT NULL,
    version_no INTEGER NOT NULL,
    source VARCHAR(20) NOT NULL,
    source_ref VARCHAR(20),
    question VARCHAR(60) NOT NULL,
    description VARCHAR(80) NOT NULL,
    category VARCHAR(30) NOT NULL,
    difficulty VARCHAR(20) NOT NULL,
    option_a_label VARCHAR(20) NOT NULL,
    option_a_rationale VARCHAR(40) NOT NULL,
    option_a_philosopher VARCHAR(20) NOT NULL,
    option_b_label VARCHAR(20) NOT NULL,
    option_b_rationale VARCHAR(40) NOT NULL,
    option_b_philosopher VARCHAR(20) NOT NULL,
    profile_version VARCHAR(30) NOT NULL,
    prompt_version VARCHAR(30),
    created_at TIMESTAMP,
    updated_at TIMESTAMP,
    CONSTRAINT uk_class_topic_versions_draft_version UNIQUE (draft_id, version_no)
);

DO $$
BEGIN
    IF NOT EXISTS (SELECT 1 FROM pg_constraint WHERE conname = 'fk_class_topic_drafts_owner') THEN
        ALTER TABLE class_topic_drafts ADD CONSTRAINT fk_class_topic_drafts_owner
            FOREIGN KEY (owner_id) REFERENCES users(id);
    END IF;
    IF NOT EXISTS (SELECT 1 FROM pg_constraint WHERE conname = 'fk_class_topic_drafts_ticket') THEN
        ALTER TABLE class_topic_drafts ADD CONSTRAINT fk_class_topic_drafts_ticket
            FOREIGN KEY (ticket_id) REFERENCES class_tickets(id);
    END IF;
    IF NOT EXISTS (SELECT 1 FROM pg_constraint WHERE conname = 'fk_class_topic_versions_draft') THEN
        ALTER TABLE class_topic_versions ADD CONSTRAINT fk_class_topic_versions_draft
            FOREIGN KEY (draft_id) REFERENCES class_topic_drafts(id);
    END IF;
END $$;

CREATE INDEX IF NOT EXISTS idx_class_topic_drafts_owner ON class_topic_drafts (owner_id);
CREATE INDEX IF NOT EXISTS idx_class_topic_versions_draft_source_ref ON class_topic_versions (draft_id, source_ref);
-- 분당 요청 제한 조회 (countByTicketIdAndTypeAndStartedAtAfter)
CREATE INDEX IF NOT EXISTS idx_ai_jobs_ticket_type_started ON ai_jobs (ticket_id, type, started_at);
