CREATE TABLE IF NOT EXISTS class_debate_sessions (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    class_id BIGINT NOT NULL,
    member_id BIGINT NOT NULL,
    participant_option_id BIGINT NOT NULL,
    opponent_option_id BIGINT NOT NULL,
    philosopher VARCHAR(20) NOT NULL,
    status VARCHAR(20) NOT NULL,
    current_round INTEGER NOT NULL,
    generating_started_at TIMESTAMP,
    completed_at TIMESTAMP,
    created_at TIMESTAMP,
    updated_at TIMESTAMP,
    CONSTRAINT uk_class_debate_sessions_class_member UNIQUE (class_id, member_id)
);

CREATE TABLE IF NOT EXISTS class_debate_messages (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    session_id BIGINT NOT NULL,
    round_index INTEGER NOT NULL,
    speaker VARCHAR(10) NOT NULL,
    content TEXT NOT NULL,
    focus VARCHAR(20),
    reply_to_message_id BIGINT,
    request_key VARCHAR(64),
    created_at TIMESTAMP,
    updated_at TIMESTAMP,
    CONSTRAINT uk_class_debate_messages_turn UNIQUE (session_id, round_index, speaker)
);

DO $$
BEGIN
    IF NOT EXISTS (SELECT 1 FROM pg_constraint WHERE conname = 'fk_class_debate_sessions_class') THEN
        ALTER TABLE class_debate_sessions ADD CONSTRAINT fk_class_debate_sessions_class
            FOREIGN KEY (class_id) REFERENCES classes(id);
    END IF;
    IF NOT EXISTS (SELECT 1 FROM pg_constraint WHERE conname = 'fk_class_debate_sessions_member') THEN
        ALTER TABLE class_debate_sessions ADD CONSTRAINT fk_class_debate_sessions_member
            FOREIGN KEY (member_id) REFERENCES class_members(id);
    END IF;
    IF NOT EXISTS (SELECT 1 FROM pg_constraint WHERE conname = 'fk_class_debate_sessions_participant_option') THEN
        ALTER TABLE class_debate_sessions ADD CONSTRAINT fk_class_debate_sessions_participant_option
            FOREIGN KEY (participant_option_id) REFERENCES battle_options(id);
    END IF;
    IF NOT EXISTS (SELECT 1 FROM pg_constraint WHERE conname = 'fk_class_debate_sessions_opponent_option') THEN
        ALTER TABLE class_debate_sessions ADD CONSTRAINT fk_class_debate_sessions_opponent_option
            FOREIGN KEY (opponent_option_id) REFERENCES battle_options(id);
    END IF;
    IF NOT EXISTS (SELECT 1 FROM pg_constraint WHERE conname = 'fk_class_debate_messages_session') THEN
        ALTER TABLE class_debate_messages ADD CONSTRAINT fk_class_debate_messages_session
            FOREIGN KEY (session_id) REFERENCES class_debate_sessions(id) ON DELETE CASCADE;
    END IF;
END $$;
