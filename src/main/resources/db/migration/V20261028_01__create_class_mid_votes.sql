-- #577 클래스 중간투표: 선택 지점(scenario_nodes.id)별 1건 (PRD §7 "checkpoint_id별 기록")
-- checkpoint_id / option_id 는 시나리오 재저장 시 바뀔 수 있어 FK 를 걸지 않고 선택 당시 문구를 함께 저장한다.
-- 멱등하게 작성되어 재실행해도 안전하다.

CREATE TABLE IF NOT EXISTS class_mid_votes (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    vote_id BIGINT NOT NULL,
    checkpoint_id BIGINT NOT NULL,
    option_id BIGINT NOT NULL,
    option_label VARCHAR(255) NOT NULL,
    created_at TIMESTAMP,
    updated_at TIMESTAMP,
    CONSTRAINT uk_class_mid_votes_checkpoint UNIQUE (vote_id, checkpoint_id)
);

DO $$
BEGIN
    IF NOT EXISTS (SELECT 1 FROM pg_constraint WHERE conname = 'fk_class_mid_votes_vote') THEN
        ALTER TABLE class_mid_votes ADD CONSTRAINT fk_class_mid_votes_vote
            FOREIGN KEY (vote_id) REFERENCES votes(id) ON DELETE CASCADE;
    END IF;
END $$;
