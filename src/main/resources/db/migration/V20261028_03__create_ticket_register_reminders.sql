-- #589 미등록 이용권 등록기한 임박 알림(D30·D7) 발송 이력.
-- 운영자가 허용된 연락 수단으로 보낸 결과를 기록한다. 같은 단계에 실패 후 재시도할 수 있어 단계별 UNIQUE 를 두지 않는다.
-- 멱등하게 작성되어 재실행해도 안전하다.

CREATE TABLE IF NOT EXISTS ticket_register_reminders (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    ticket_id BIGINT NOT NULL,
    stage VARCHAR(10) NOT NULL,
    channel VARCHAR(20) NOT NULL,
    status VARCHAR(20) NOT NULL,
    failure_reason VARCHAR(255),
    attempted_at TIMESTAMP NOT NULL,
    created_at TIMESTAMP,
    updated_at TIMESTAMP
);

CREATE INDEX IF NOT EXISTS idx_ticket_register_reminders_ticket_stage
    ON ticket_register_reminders (ticket_id, stage);

DO $$
BEGIN
    IF NOT EXISTS (SELECT 1 FROM pg_constraint WHERE conname = 'fk_ticket_register_reminders_ticket') THEN
        ALTER TABLE ticket_register_reminders ADD CONSTRAINT fk_ticket_register_reminders_ticket
            FOREIGN KEY (ticket_id) REFERENCES class_tickets(id) ON DELETE CASCADE;
    END IF;
END $$;
